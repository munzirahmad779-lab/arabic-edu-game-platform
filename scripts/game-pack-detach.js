#!/usr/bin/env node

/**
 * Unplug the optional games pack while leaving a buildable lightweight app.
 *
 * Override the destination with MAGGURU_GAMES_PACK_DIR when needed.
 * Default Windows path: D:\\game
 */
const fs = require("fs");
const path = require("path");

const repoRoot = path.resolve(__dirname, "..");
const packDir = path.join(repoRoot, "src", "modules", "games-pack");
const standaloneDir = path.resolve(
  process.env.MAGGURU_GAMES_PACK_DIR || path.join(repoRoot, "..", "game"),
);

const stub = `/** Generated by scripts/game-pack-detach.js. Do not edit. */
import type { ComponentType } from "react";

export type GameLoader = () => Promise<{ default: ComponentType }>;
export const GAME_PACK_AVAILABLE = false;
export const GAME_REGISTRY: Record<string, GameLoader> = {};
export const GAME_SLUGS: readonly string[] = [];
export const GAME_CATALOG: readonly never[] = [];
export function hasGameEngine(_slug: string): boolean {
  return false;
}
`;

if (!fs.existsSync(packDir)) {
  console.error(`Games pack tidak ditemukan di ${packDir}`);
  process.exit(1);
}

const currentRegistry = path.join(packDir, "games-registry.ts");
if (fs.existsSync(currentRegistry) && /GAME_PACK_AVAILABLE\s*=\s*false/.test(fs.readFileSync(currentRegistry, "utf8"))) {
  console.log("Games pack sudah dalam mode detached.");
  process.exit(0);
}

if (fs.existsSync(standaloneDir)) {
  console.error(`Tujuan standalone sudah ada: ${standaloneDir}`);
  console.error("Pindahkan atau hapus tujuan tersebut secara manual sebelum detach ulang.");
  process.exit(1);
}

const parentDir = path.dirname(standaloneDir);
if (parentDir && parentDir !== path.parse(parentDir).root && !fs.existsSync(parentDir)) {
  fs.mkdirSync(parentDir, { recursive: true });
}
fs.renameSync(packDir, standaloneDir);
fs.mkdirSync(packDir, { recursive: true });
fs.writeFileSync(path.join(packDir, "games-registry.ts"), stub, "utf8");

console.log(`Games pack dilepas ke: ${standaloneDir}`);
console.log("Fallback mode aktif: /games/<slug> menampilkan placeholder ringan.");
